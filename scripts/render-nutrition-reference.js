// Development utility only: refresh the static reference page after editing nutrition data.
const fs = require('node:fs');
const path = require('node:path');
const { NUTRITION, INGREDIENT_BLENDS } = require('../recipe-data');
const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
const n = value => Number(value.toFixed(4));
const entries = Object.entries(NUTRITION).sort(([a], [b]) => a.localeCompare(b));
const cards = entries.map(([name, ref]) => {
  const units = Object.entries(ref.gramsPerUnit).map(([unit, grams]) => `1 ${unit} = ${n(grams)} g`).join('; ') || 'Weight units only; no household conversion assumed.';
  return `<details class="nutrition-reference-entry">
<summary>${escape(name)} — ${escape(ref.preparation)}</summary>
<p>Per ${ref.reference.amount} g: ${ref.macros.calories} kcal; protein ${ref.macros.protein} g; carbohydrates ${ref.macros.carbs} g; fat ${ref.macros.fat} g.</p>
<p>Reference measures: ${escape(units)}</p>
${ref.note ? `<p>${escape(ref.note)}</p>` : ''}
<p><a href="${escape(ref.source.url)}" target="_blank" rel="noopener">${escape(ref.source.title)}</a> (${escape(ref.source.dataset)}; checked ${escape(ref.source.checked)}).</p>
</details>`;
}).join('\n');
const blends = Object.entries(INGREDIENT_BLENDS).map(([name, blend]) => `<li><strong>${escape(name)}</strong>: each recipe portion (${escape(blend.unit)} in the template) expands to ${blend.components.map(([name, grams]) => `${n(grams)} g ${escape(name)}`).join(', ')}.</li>`).join('\n');
const html = `<!doctype html>
<!-- Generated by node scripts/render-nutrition-reference.js. Edit nutrition-data.js, not the food cards here. -->
<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>PrepFit nutrition references</title><link rel="stylesheet" href="styles.css"></head>
<body><main class="nutrition-reference-page">
<a href="index.html">Back to PrepFit</a>
<h1>Nutrition references</h1>
<p>These are estimates for specific foods and preparation states. Choose the matching reference product, or compare its label before relying on the estimate. Reference data checked September 9, 2026.</p>
<section class="panel"><h2>How to measure your ingredients</h2>
<ul>
<li>Use the gram weight shown in the recipe when household measures or package sizes differ.</li>
<li>Meat weights are cooked edible weights; potatoes and most vegetables are weighed raw. Rice and legumes are measured cooked and drained; pasta and oats are weighed dry. Follow each ingredient's preparation state.</li>
<li>Shopping quantities describe the required ingredient state, not an assumed raw purchase weight. Cooking yield varies; use your package yield or weigh after cooking.</li>
<li>One US customary cup equals 16 tablespoons or 48 teaspoons. Ounces are weight; fluid ounces are volume. Each food has its own reference weight for household measures. When USDA lists different rounded household weights, PrepFit selects one volume basis consistently.</li>
<li>Whey powder is a generic USDA reference, weighed in grams. Supplemental protein means grams of protein, not grams of powder; its other macros and shopping weight are calculated from that same reference. Different brands and scoops vary.</li>
<li>Patak's sauce labels report protein as &lt;1 g per 64 g. PrepFit uses zero as a conservative lower bound; actual protein can be up to (but less than) one extra gram per reference serving. Other label values are rounded by their sources.</li>
<li>Recipes include only listed ingredients plus water. Additional oils, toppings, or seasonings are outside the estimate and may conflict with your exclusions.</li>
</ul>
<p>USDA records come from the <a href="https://fdc.nal.usda.gov/download-datasets/">SR Legacy dataset</a>. Manufacturer panels are linked below. Measurement conventions follow <a href="https://nvlpubs.nist.gov/nistpubs/Legacy/LC/nbslettercircular1098.pdf">NIST US customary conversions</a>. Values describe reference foods, not laboratory analysis of your prepared meal.</p>
</section>
<section class="panel"><h2>Explicit mixes and sauces</h2>
<p>These are PrepFit recipes, not nutrition estimates for unspecified store-bought mixes. Their components appear separately in ingredient and grocery lists. Template portions scale the component recipe; they do not claim a measured final mixture volume.</p>
<ul>${blends}</ul></section>
<section class="panel"><h2>Ingredient sources and servings</h2>
<p>Expand an ingredient to see its reference values, preparation state, household weights, and source.</p>
${cards}</section>
</main></body></html>\n`;
if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, '..', 'nutrition.html'), html);
  console.log(`Updated nutrition.html with ${entries.length} references.`);
}
module.exports = html;
